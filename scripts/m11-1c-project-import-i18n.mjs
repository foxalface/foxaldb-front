const insertAfterHint = /( {20}invalid_diagram_json_hint:[^\n]*\n)/;

for (const locale of Object.keys(blocks)) {
    const path = join(localesDir, `${locale}.ts`);
    let source = readFileSync(path, 'utf8');

    if (source.includes('errors:') && source.includes('project_import:')) {
        const errorsIndex = source.indexOf(
            '                errors: {',
            source.indexOf('import_schema:')
        );
        const projectImportIndex = source.indexOf(
            'project_import:',
            errorsIndex
        );
        if (projectImportIndex !== -1) {
            console.log(`Skip ${locale}: already has project_import in errors`);
            continue;
        }
    }

    const match = source.match(insertAfterHint);
    if (!match) {
        throw new Error(`hint line not found in ${locale}`);
    }

    source = source.replace(insertAfterHint, `${match[1]}${blocks[locale]}`);
    writeFileSync(path, source);
    console.log(`Updated ${locale}`);
}
